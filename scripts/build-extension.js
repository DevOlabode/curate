#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { main: generateIcons } = require('./generate-icons');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'dist/extension');
const SOURCE = path.join(ROOT, 'extension');
const SHARED = path.join(ROOT, 'src/shared');

const PRODUCTION_API = 'https://curate-eight-omega.vercel.app';
const LOCAL_API = 'http://localhost:3000';

// Changing this list can show users a new permission warning, which disables
// the extension until they accept it. Only add permissions without a warning.
const ALLOWED_PERMISSIONS = ['storage', 'activeTab'];

// Build variants:
//   production  - the store build; talks only to the production API
//   staging     - "Curate (Staging)", talks only to STAGING_API_URL; load unpacked, never upload
//   development - production API plus localhost, for local work (default)
function buildTarget(argv = process.argv) {
  const flag = argv.find((arg) => arg.startsWith('--env='));
  const env = flag ? flag.slice('--env='.length) : 'development';
  if (env === 'production') return { env, apiUrls: [PRODUCTION_API] };
  if (env === 'development') return { env, apiUrls: [PRODUCTION_API, LOCAL_API] };
  if (env === 'staging') {
    const url = String(process.env.STAGING_API_URL || '').replace(/\/$/, '');
    if (!/^https:\/\//.test(url)) {
      throw new Error('Staging builds need STAGING_API_URL=https://… (the Vercel staging URL)');
    }
    return { env, apiUrls: [url] };
  }
  throw new Error(`Unknown --env=${env} (use production, staging or development)`);
}

const EXCLUDE = new Set([
  '.DS_Store',
  '.env',
  '.env.local',
  'node_modules',
]);

function copyEntry(src, dest) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    copyDir(src, dest);
    return;
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyDir(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    if (EXCLUDE.has(name)) continue;
    copyEntry(path.join(src, name), path.join(dest, name));
  }
}

function applyTarget(dir, target) {
  const manifestPath = path.join(dir, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const hosts = target.apiUrls.map((url) => `${url}/*`);

  manifest.host_permissions = hosts;
  manifest.content_security_policy.extension_pages = manifest.content_security_policy.extension_pages
    .replace(/connect-src [^;]*/, `connect-src 'self' ${target.apiUrls.join(' ')}`);
  if (target.env === 'staging') {
    manifest.name = 'Curate (Staging)';
    manifest.action.default_title = 'Curate (Staging)';
  }
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  fs.writeFileSync(
    path.join(dir, 'shared/build-env.js'),
    `// Generated by scripts/build-extension.js. Do not edit.\n` +
      `export const BUILD_ENV = ${JSON.stringify(target.env)};\n` +
      `export const BUILD_API_URL = ${JSON.stringify(target.apiUrls[0])};\n`
  );
}

function checkTarget(dir, target) {
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
  const extra = manifest.permissions.filter((p) => !ALLOWED_PERMISSIONS.includes(p));
  if (extra.length) {
    throw new Error(`Permission(s) not on the allowlist: ${extra.join(', ')}. See ALLOWED_PERMISSIONS.`);
  }
  if (target.env === 'production') {
    const text = JSON.stringify(manifest);
    if (/localhost|127\.0\.0\.1|staging/i.test(text)) {
      throw new Error('Production manifest must not reference localhost or staging');
    }
  }
  console.log(`[build:extension] ${target.env} build checked`);
}

function validateManifest(dir) {
  const manifestPath = path.join(dir, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

  if (manifest.manifest_version !== 3) {
    throw new Error('manifest_version must be 3');
  }

  const required = ['name', 'version', 'action', 'background', 'permissions'];
  required.forEach((key) => {
    if (!(key in manifest)) {
      throw new Error(`manifest.json missing required key: ${key}`);
    }
  });

  for (const size of ['16', '32', '48', '128']) {
    const iconPath = path.join(dir, manifest.icons[size]);
    if (!fs.existsSync(iconPath)) {
      throw new Error(`Missing icon file: ${manifest.icons[size]}`);
    }
  }

  console.log('[build:extension] manifest.json validated');
}

function main() {
  const target = buildTarget();
  console.log(`[build:extension] target: ${target.env}`);
  console.log('[build:extension] generating icons…');
  generateIcons();

  console.log('[build:extension] cleaning dist/extension…');
  fs.rmSync(OUT, { recursive: true, force: true });

  console.log('[build:extension] copying extension sources…');
  copyDir(SOURCE, OUT);

  console.log('[build:extension] copying shared modules…');
  copyDir(SHARED, path.join(OUT, 'shared'));

  const logoSrc = path.join(ROOT, 'public/images/download.svg');
  const logoDest = path.join(OUT, 'assets/logo.svg');
  fs.mkdirSync(path.dirname(logoDest), { recursive: true });
  fs.copyFileSync(logoSrc, logoDest);
  console.log('[build:extension] copied assets/logo.svg');

  applyTarget(OUT, target);
  validateManifest(OUT);
  checkTarget(OUT, target);

  console.log(`[build:extension] done → ${OUT}`);
}

main();
